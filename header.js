export function initHeader() {
    if (navigator.userAgent.match(/Mobi|Android|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i)) {
        window.location.href = window.location.origin + '/www/h5/index.html';
    }
    const params = new URLSearchParams(window.location.search);
    const id = params.get('id') || 'index';
    if (id) {
        document.querySelectorAll("#nav1 div").forEach((div) => {
            div.classList.remove("addChecked1", "addChecked2");
        });

        const targetDiv = document.getElementById(id);
        const headDiv = document.getElementById("header");
        const logoDiv = document.getElementById("logo1");
        const logo2Div = document.getElementById("logo2");
        const loginDiv = document.getElementById("login1");
        const login2Div = document.getElementById("login2");

        if (id === "index") {
            logoDiv.classList.remove("hidden");
            logo2Div.classList.add("hidden");
            loginDiv.classList.remove("hidden");
            login2Div.classList.add("hidden");
        } else {
            logo2Div.classList.remove("hidden");
            logoDiv.classList.add("hidden");
            login2Div.classList.remove("hidden");
            loginDiv.classList.add("hidden");
        }
        headDiv.classList.remove("header1", "header2");
        headDiv.classList.add(id === "index" ? "header1" : "header2");
        headDiv.classList.add("fixedHeader");
        if (targetDiv) {
            targetDiv.classList.add(id === "index" ? "addChecked1" : "addChecked2");
        }
    }
    return true;
}
